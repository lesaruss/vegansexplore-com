-- ve-vegan-sourcing-guide (Logan, 2026-11-04). The shared sourcing directory: its own table, never `listings`,
-- so the nightly outreach, logo, audit and essentials jobs cannot touch it. A supplier becomes a Directory listing
-- only when it claims its page (listing_id). RLS on, no policies: everything goes through the ve-sourcing function.
create table if not exists ve_suppliers (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  website text,
  domain text not null default 'materials' check (domain in ('food_drink','ingredients','packaging','co_packing','machinery','materials','distribution','certification')),
  kinds text[] not null default '{}',
  label text not null default 'offers_options' check (label in ('peta_approved','fully_vegan','offers_options')),
  bio text,
  bio_source text,
  status text not null default 'active' check (status in ('active','hidden','removed')),
  source text,
  listing_id uuid,
  checked_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table ve_suppliers enable row level security;
create index if not exists ve_suppliers_domain_idx on ve_suppliers (domain, status);
